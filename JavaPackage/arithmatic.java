package JavaPackage;

class Arithmatic {

    int sum(int a, int b) {
        return a + b;
    }

    int sub(int a, int b) {
        return a - b;
    }

    int multi(int a, int b) {
        return a * b;
    }

    int divid(int a, int b) {
        return a / b;
    }

    int modulo(int a, int b) {
        return a % b;
    }

}
