class typecasting
{
public static void main(String arg[])
{
int a = 10;
double b;
b = (long)a;

System.out.println(a);
System.out.println(b);

//--------single line comment---------

long r = 100;
double s;
s = (long)r;

System.out.println(r);
System.out.println(s );



double t = 100.8;
long u;
u = (long)t;

System.out.println(t);
System.out.println(u );

}
}